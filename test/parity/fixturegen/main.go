// Command fixturegen writes the rewrite/java-v7-to-go/paritydiff corpus for the e2e fixture
// studies (test/parity/fixtures.txt). The requests are derived from the Java
// backend's own answers on those studies — their profiles, sample lists,
// attributes, top genes and chart values — so filters hit real data and the
// corpus follows the fixtures. See docs/testing.md ("Java oracle").
//
//	go run ./test/parity/fixturegen -java http://localhost:18095 > test/parity/fixtures.txt
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"strings"
	"time"
)

var javaURL = flag.String("java", "http://localhost:18095", "Java backend serving the fixture studies")

type request struct {
	Name   string
	Method string
	Path   string
	Body   any
}

var client = &http.Client{Timeout: 120 * time.Second}

// javaJSON fetches from the Java backend while building the corpus.
func javaJSON(method, path string, body any) any {
	var rd io.Reader
	if body != nil {
		b, _ := json.Marshal(body)
		rd = bytes.NewReader(b)
	}
	req, _ := http.NewRequest(method, *javaURL+path, rd)
	req.Header.Set("Content-Type", "application/json")
	resp, err := client.Do(req)
	if err != nil {
		fmt.Fprintf(os.Stderr, "fixturegen: %s %s: %v\n", method, path, err)
		return nil
	}
	defer resp.Body.Close()
	b, _ := io.ReadAll(resp.Body)
	if resp.StatusCode != 200 {
		fmt.Fprintf(os.Stderr, "fixturegen: %s %s -> %d %.200s\n", method, path, resp.StatusCode, b)
		return nil
	}
	var v any
	json.Unmarshal(b, &v)
	return v
}

func list(v any) []map[string]any {
	a, _ := v.([]any)
	out := make([]map[string]any, 0, len(a))
	for _, x := range a {
		if m, ok := x.(map[string]any); ok {
			out = append(out, m)
		}
	}
	return out
}

func str(v any) string {
	switch x := v.(type) {
	case string:
		return x
	case nil:
		return ""
	}
	return fmt.Sprint(v)
}

func main() {
	flag.Parse()
	fmt.Println("# API parity corpus on cBioPortal's e2e fixture studies, for rewrite/java-v7-to-go/paritydiff")
	fmt.Println("# against the Java backend (docs/testing.md, \"Java oracle\"). Generated by")
	fmt.Println("# test/parity/fixturegen from the Java backend's answers; regenerate rather")
	fmt.Println("# than edit.")
	seen := map[string]bool{}
	names := map[string]int{}
	for _, r := range buildCorpus() {
		body := ""
		if r.Body != nil {
			b, _ := json.Marshal(r.Body)
			body = string(b)
		}
		key := r.Method + " " + r.Path + " " + body
		if seen[key] {
			continue
		}
		seen[key] = true
		// Names become file names in paritydiff -dump.
		name := strings.ReplaceAll(r.Name, "/", ":")
		if names[name]++; names[name] > 1 {
			name = fmt.Sprintf("%s#%d", name, names[name])
		}
		fmt.Printf("## %s\n%s %s\n", name, r.Method, r.Path)
		if body != "" {
			fmt.Println(body)
		}
	}
}
